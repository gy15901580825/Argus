"""Extract IDs and display names from the hash-verified, pinned ATLAS release.

Download the source_url in argus/data/atlas_mitigations.yaml, then run:
    python scripts/gen_atlas_techniques.py --source ATLAS-2026.10.yaml
Use --check to verify the checked-in list without writing it.
"""
from __future__ import annotations

import argparse
import hashlib
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
METADATA_FIELDS = (
    "framework", "version", "modified_date", "source_url", "source_commit", "source_sha256",
)


def extract(source_bytes: bytes, metadata: dict) -> dict:
    if hashlib.sha256(source_bytes).hexdigest() != metadata["source_sha256"]:
        raise ValueError("ATLAS source SHA256 differs from the pinned source_sha256")
    source = yaml.safe_load(source_bytes)
    if source["collection"]["version"] != metadata["version"]:
        raise ValueError("ATLAS source version differs from the pinned version")
    techniques = source["techniques"]
    names = {}
    for technique_id, technique in sorted(techniques.items()):
        name = technique["name"]
        if "." in technique_id.removeprefix("AML."):
            parent = technique_id.rsplit(".", 1)[0]
            name = f'{techniques[parent]["name"]}: {name}'
        names[technique_id] = name
    return {**{key: metadata[key] for key in METADATA_FIELDS}, "techniques": names}


def render(data: dict) -> str:
    return "# Generated by scripts/gen_atlas_techniques.py; do not edit.\n" + yaml.safe_dump(
        data, sort_keys=False, allow_unicode=True, width=100,
    )


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source", required=True, type=Path)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    metadata = yaml.safe_load((ROOT / "argus/data/atlas_mitigations.yaml").read_text())
    generated = render(extract(args.source.read_bytes(), metadata))
    target = ROOT / "argus/data/atlas_techniques.yaml"
    if args.check:
        if target.read_text() != generated:
            parser.exit(1, "atlas_techniques.yaml is stale; regenerate from the pinned source\n")
    else:
        target.write_text(generated)


if __name__ == "__main__":
    main()
