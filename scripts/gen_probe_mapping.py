"""Generate docs/probe-mapping.md — printed to stdout.

The doc used to be hand-written and drifted from what the code actually
computes: it counted one "primary" OWASP category per probe, while
`build_coverage` (the same function behind `GET /redteam/coverage` and
`argus-probe coverage`) counts every mapping a probe declares. Neither
number was wrong, but a public repo holding two contradictory coverage
tables is not something we can afford. This script is now the only source
of the doc; `tests/test_probe_mapping_doc_is_current.py`
fails if the checked-in file falls out of sync with it.

Usage (from the repo root):
    python scripts/gen_probe_mapping.py > docs/probe-mapping.md
"""

from __future__ import annotations

import sys
import argparse
from pathlib import Path

# Run as a plain script, so Python only puts scripts/ on sys.path.
# Add the repo root so `argus.*` resolves to this checkout.
sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from argus.coverage import OWASP_LLM_TOP10, build_coverage  # noqa: E402
from argus.agentic import OWASP_AGENTIC_METADATA, VALID_OWASP_AGENTIC_IDS  # noqa: E402
from argus.probe import load_all_probes  # noqa: E402
from argus.atlas import ATLAS_METADATA, invalid_atlas_ids  # noqa: E402

PROBES_DIR = Path(__file__).resolve().parent.parent / "argus" / "probes"

_VALID_OWASP_IDS = frozenset(cell_id for cell_id, _name in OWASP_LLM_TOP10)

_STANDARD_LABELS = (
    ("owasp-llm-top10", "OWASP LLM Top 10"),
    ("owasp-agentic-top10", "OWASP Agentic Top 10"),
    ("mitre-atlas", "MITRE ATLAS"),
    ("nist-ai-rmf", "NIST AI RMF"),
    ("eu-ai-act", "EU AI Act"),
)


def invalid_owasp_ids(probes) -> list[tuple[str, str]]:
    """(probe_id, bad_id) for every probe declaring an OWASP id outside LLM01-LLM10.

    Such an id is silently dropped from the closed-universe OWASP cells in
    `build_coverage` — the run can only look less tested, never more, but a
    typo like `LLM011` would erase that probe's coverage with no signal.
    ATLAS labels are validated separately against the pinned release.
    """
    return [
        (probe.id, owasp_id)
        for probe in probes
        for owasp_id in probe.mappings.owasp_llm
        if owasp_id not in _VALID_OWASP_IDS
    ]


def invalid_owasp_agentic_ids(probes) -> list[tuple[str, str]]:
    """Return agentic tags outside the official, closed ASI01-ASI10 taxonomy."""
    return [
        (probe.id, agentic_id)
        for probe in probes
        for agentic_id in probe.mappings.owasp_agentic
        if agentic_id not in VALID_OWASP_AGENTIC_IDS
    ]


def invalid_attack_eu_labels(probes) -> list[tuple[str, str]]:
    """Article 15(3) concerns declared accuracy metrics, not attack resilience."""
    return [
        (probe.id, article)
        for probe in probes
        for article in probe.mappings.eu_ai_act
        if probe.attack_class and article == "Article 15(3)"
    ]


def render(probes: list) -> str:
    coverage = build_coverage(probes)
    owasp_cells = coverage["standards"]["owasp-llm-top10"]["cells"]

    lines = []
    lines.append("# Probe -> Standards Mapping")
    lines.append("")
    lines.append(
        "Generated by `scripts/gen_probe_mapping.py` from `build_coverage` "
        "(the same function behind `GET /redteam/coverage` and `argus-probe coverage`). "
        "Do not hand-edit it. Regenerate it with `python scripts/gen_probe_mapping.py > "
        "docs/probe-mapping.md` from the repo root."
    )
    lines.append("")
    lines.append(
        "Counts below are **every mapping a probe declares**, not one \"primary\" category "
        "per probe. An earlier, hand-written version of this table counted one category per "
        "probe, which is why its numbers did not match what the code computes."
    )
    lines.append("")
    lines.append(f"`{len(probes)}` probes in the library.")
    lines.append("")
    lines.append("## OWASP LLM Top 10")
    lines.append("")
    lines.append("| OWASP | Category | Probes in library | Library status |")
    lines.append("|---|---|---:|---|")
    for cell in owasp_cells:
        lines.append(f"| {cell['id']} | {cell['name']} | {cell['probes_in_library']} | {cell['library_status']} |")
    lines.append("")
    lines.append("## OWASP Agentic Top 10")
    lines.append("")
    lines.append(
        f"[OWASP Top 10 for Agentic Applications, {OWASP_AGENTIC_METADATA['edition']} edition]"
        f"({OWASP_AGENTIC_METADATA['source_url']}), published {OWASP_AGENTIC_METADATA['published']}. "
        "Agentic mappings are direct-risk tags: they identify the risk a probe actually exercises. "
        "Related prerequisites and possible downstream effects do not earn a tag. "
        "A cell marked `absent` has no mapped probe; these counts do not establish "
        "complete coverage or compliance. See [mapping rationale](owasp-agentic-mapping.md) "
        "for the evidence behind these assignments."
    )
    lines.append("")
    lines.append("| OWASP Agentic | Category | Probes in library | Library status |")
    lines.append("|---|---|---:|---|")
    for cell in coverage["standards"]["owasp-agentic-top10"]["cells"]:
        lines.append(f"| {cell['id']} | {cell['name']} | {cell['probes_in_library']} | {cell['library_status']} |")
    lines.append("")
    lines.append("## MITRE ATLAS")
    lines.append("")
    lines.append(
        f'Labels and names use [ATLAS {ATLAS_METADATA["version"]}]'
        f'({ATLAS_METADATA["source_url"]}). Counts describe declared probe mappings.'
    )
    lines.append("")
    lines.append("| ATLAS | Technique | Probes in library |")
    lines.append("|---|---|---:|")
    for cell in coverage["standards"]["mitre-atlas"]["cells"]:
        lines.append(f"| {cell['id']} | {cell.get('name', '')} | {cell['probes_in_library']} |")
    lines.append("")
    lines.append("## EU AI Act")
    lines.append("")
    lines.append(
        "Article 15(5) addresses resilience to third-party attacks. "
        "Article 15(3) addresses declared accuracy metrics and is not an attack-probe label."
    )
    lines.append("")
    lines.append("| Article | Probes in library |")
    lines.append("|---|---:|")
    for cell in coverage["standards"]["eu-ai-act"]["cells"]:
        lines.append(f"| {cell['id']} | {cell['probes_in_library']} |")
    lines.append("")
    lines.append("## Cells touched, per standard")
    lines.append("")
    lines.append("| Standard | Cells touched |")
    lines.append("|---|---:|")
    for key, label in _STANDARD_LABELS:
        cells = coverage["standards"][key]["cells"]
        touched = sum(1 for c in cells if c["probes_in_library"] > 0)
        lines.append(f"| {label} ({key}) | {touched} |")
    lines.append("")
    lines.append("## Probes")
    lines.append("")
    lines.append("| Probe ID | Attack class | Technique | Severity | Target class | OWASP Agentic IDs |")
    lines.append("|---|---|---|---|---|---|")
    for probe in sorted(probes, key=lambda p: p.id):
        attack_class = ",".join(probe.attack_class)
        technique = ",".join(probe.technique)
        target_class = ",".join(probe.target_class)
        agentic = ", ".join(probe.mappings.owasp_agentic) or "[]"
        lines.append(f"| `{probe.id}` | {attack_class} | {technique} | {probe.severity} | {target_class} | {agentic} |")
    lines.append("")
    return "\n".join(lines)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--probes-dir", type=Path, default=PROBES_DIR)
    parser.add_argument("--check", action="store_true", help="Validate labels without rendering docs")
    args = parser.parse_args()
    probes = list(load_all_probes(args.probes_dir))

    bad_labels = invalid_atlas_ids(probes) + invalid_attack_eu_labels(probes)
    if bad_labels:
        print("ERROR: probe labels outside the pinned ATLAS release or attack EU policy:", file=sys.stderr)
        for probe_id, label in bad_labels:
            print(f"  {probe_id}: {label}", file=sys.stderr)
        sys.exit(1)

    bad = invalid_owasp_ids(probes)
    if bad:
        print(f"WARNING: {len(bad)} probe(s) declare an OWASP id outside LLM01-LLM10:", file=sys.stderr)
        for probe_id, owasp_id in bad:
            print(f"  {probe_id}: {owasp_id!r}", file=sys.stderr)

    bad_agentic = invalid_owasp_agentic_ids(probes)
    if bad_agentic:
        print(f"ERROR: {len(bad_agentic)} invalid OWASP Agentic id(s) outside ASI01-ASI10:", file=sys.stderr)
        for probe_id, agentic_id in bad_agentic:
            print(f"  {probe_id}: {agentic_id!r}", file=sys.stderr)
        sys.exit(1)

    if args.check:
        print(f"{len(probes)} probes have valid standards labels.")
    else:
        sys.stdout.write(render(probes))


if __name__ == "__main__":
    main()
