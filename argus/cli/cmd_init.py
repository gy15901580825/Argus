"""argus-probe init subcommand: scaffold a target.json + optional GH Action workflow."""

from __future__ import annotations

import json
import re
import shlex
import subprocess
import sys
from importlib.metadata import PackageNotFoundError, version
from pathlib import Path

import click

from argus.targets import _BUILTIN_KINDS, kinds

_DEFAULT_KIND = "openai_compat"

# Chat kinds get a small judged set. Every other kind gets `all`, because the chat probes do not
# apply to it and would be skipped, leaving a job that tests nothing. Assumes `all` fits the target (PR5a).
_CHAT_PROBES = "owasp_01_prompt_injection_basic,syscard_crescendo"


def _probes_for(kind: str) -> str:
    info = _BUILTIN_KINDS.get(kind) or kinds()[kind]
    return _CHAT_PROBES if info.chat else "all"


_WORKFLOW_TEMPLATE = """\
# .github/workflows/argus-probe.yml
# Generated by `argus-probe init`. Customize as needed.
name: argus-probe
'on':
{branch_triggers}  schedule:
    # Weekly Monday 06:00 UTC
    - cron: '0 6 * * 1'
  workflow_dispatch: {{}}

jobs:
  redteam:
    if: ${{{{ github.actor != 'dependabot[bot]' && (github.event_name != 'pull_request' || github.event.pull_request.head.repo.full_name == github.repository) }}}}
    runs-on: ubuntu-latest
    timeout-minutes: 30
    permissions:
      security-events: write   # SARIF upload
      contents: read
    steps:
      - uses: actions/checkout@v4
      - uses: gy15901580825/argus-probe-action@v2
        env:
          # The LLM judge.
          ANTHROPIC_API_KEY: ${{{{ secrets.ANTHROPIC_API_KEY }}}}
{target_env}        with:
          target: {target_path}
          probes: {probes}
          fail-on: critical
          output: argus.sarif
{version_line}      - name: Upload Argus report
        if: always()
        uses: actions/upload-artifact@v4
        with:
          name: argus-report
          path: argus.sarif
          if-no-files-found: warn
"""


def _git_output(*args: str) -> str | None:
    try:
        result = subprocess.run(
            ["git", *args], capture_output=True, text=True, timeout=5,
        )
    except (OSError, subprocess.TimeoutExpired):
        return None
    return result.stdout.strip() if result.returncode == 0 else None


def _installed_version() -> str | None:
    try:
        return version("argus-probe")
    except PackageNotFoundError:  # a source tree that was never installed
        return None


def _stdin_is_tty() -> bool:
    return sys.stdin.isatty()


def _ask_kind() -> str:
    descriptions = {kind: info.description for kind, info in kinds().items()}
    if not _stdin_is_tty():
        raise click.UsageError(
            "Missing option '--kind'. stdin is not a terminal, so init cannot ask for it. "
            f"Choose one of: {', '.join(descriptions)}. "
            f"Example: argus-probe init --kind {_DEFAULT_KIND}"
        )
    width = max(map(len, descriptions))
    click.echo("Which kind of target do you want to test?")
    for name, description in descriptions.items():
        click.echo(f"  {name.ljust(width)}  {description}")
    return click.prompt(
        "Target kind",
        type=click.Choice(list(descriptions)),
        default=_DEFAULT_KIND,
        show_choices=False,
    )


class _KindChoice(click.Choice):
    def __init__(self):
        # Choices are read by Click during help, conversion and completion.
        self.case_sensitive = True

    def convert(self, value, param, ctx):
        if isinstance(value, str) and value in _BUILTIN_KINDS:
            return value
        return super().convert(value, param, ctx)

    @property
    def choices(self):
        return tuple(sorted(kinds()))


@click.command("init")
@click.option(
    "--kind",
    default=None,
    type=_KindChoice(),
    help="Target adapter kind. Asked for when omitted on a terminal.",
)
@click.option(
    "--output",
    default="argus-target.json",
    show_default=True,
    help="Output target.json path",
)
@click.option(
    "--workflow/--no-workflow",
    default=None,
    help="Generate .github/workflows/argus-probe.yml (asks on a terminal; otherwise defaults to no)",
)
@click.option("--endpoint-url", help="Target endpoint URL; otherwise use the adapter default.")
@click.option("--model", help="Target model name.")
@click.option("--api-key-env", help="Environment variable containing the target API key.")
@click.option("--set", "field_values", multiple=True, metavar="FIELD=VALUE",
              help="Set an adapter's initializer field, such as --set url=https://agent.example.")
def init_command(
    kind: str | None, output: str, workflow: bool | None,
    endpoint_url: str | None, model: str | None, api_key_env: str | None,
    field_values: tuple[str, ...],
) -> None:
    """Generate a target.json (and optional GitHub Action workflow) for Argus."""
    click.echo(f"Argus target initializer")
    if kind is None:
        kind = _ask_kind()
    click.echo(f"Target kind: {kind}")
    info = _BUILTIN_KINDS.get(kind) or kinds()[kind]
    questions = info.init_questions
    if questions is None:
        questions = tuple((field, field, None) for field in sorted(info.required)
                          if field != "sandbox" or info.sandbox_reason is None)

    interactive = _stdin_is_tty()
    supplied = {}
    for item in field_values:
        field, separator, value = item.partition("=")
        if not separator:
            raise click.UsageError("--set requires FIELD=VALUE, for example --set url=https://agent.example")
        supplied[field] = value
    supplied.update({field: value for field, value in (
        ("endpoint_url", endpoint_url), ("model", model), ("api_key_env", api_key_env),
    ) if value is not None})
    unknown = supplied.keys() - {field for field, _, _ in questions}
    if unknown:
        raise click.UsageError(f"Unknown initializer fields for {kind}: {', '.join(sorted(unknown))}. Check --set and the target kind.")
    if not interactive:
        missing = [
            f"--{field.replace('_', '-')}" if field in {"endpoint_url", "model", "api_key_env"}
            else f"--set {field}=VALUE"
            for field, _, default in questions if default is None and field not in supplied
        ]
        if missing:
            raise click.UsageError(
                f"stdin is not a terminal. Missing options: {', '.join(missing)}. "
                "Pass these options or run init on a terminal."
            )

    spec: dict[str, object] = {"kind": kind}
    for field, prompt_text, default in questions:
        if field in supplied:
            value = supplied[field]
        elif not interactive:
            value = default
        elif default is not None:
            value = click.prompt(prompt_text, default=default, show_default=True)
        else:
            value = click.prompt(prompt_text)
        spec[field] = value

    # api_key_env → api_key (CLI run command resolves $-vars at runtime)
    env_var = None
    if "api_key_env" in spec:
        env_var = str(spec.pop("api_key_env"))
        if not re.fullmatch(r"[A-Za-z_][A-Za-z0-9_]*", env_var):
            raise click.UsageError("--api-key-env must be an environment variable name, such as OPENAI_API_KEY")
        spec["api_key"] = "${" + env_var + "}"

    # inner_json → inner (payment_agent / mcp_agent / testbed_agent nest another target spec
    # for the transport that actually talks to the agent)
    if "inner_json" in spec:
        raw_inner = spec.pop("inner_json")
        try:
            spec["inner"] = json.loads(str(raw_inner))
        except json.JSONDecodeError as exc:
            raise click.UsageError(
                f"inner target spec is not valid JSON: {exc}"
            ) from exc

    if info.sandbox_reason is not None:
        spec["sandbox"] = True

    if "capabilities_csv" in spec:
        spec["capabilities"] = [
            c.strip() for c in str(spec.pop("capabilities_csv")).split(",") if c.strip()
        ]

    # Confirm-overwrite if target file exists
    target_path = Path(output)
    if target_path.exists():
        if not interactive:
            raise click.UsageError(f"{output} exists. Choose a different --output or run init on a terminal to confirm overwrite.")
        if not click.confirm(f"{output} exists. Overwrite?", default=False):
            raise click.Abort()

    if workflow is None:
        workflow = click.confirm("Generate GitHub Action workflow?", default=False) if interactive else False
    repo_root = _git_output("rev-parse", "--show-toplevel") if workflow else None
    workflow_root = Path(repo_root) if repo_root else Path.cwd()
    if workflow:
        try:
            workflow_target = target_path.resolve().relative_to(workflow_root.resolve()).as_posix()
        except ValueError as exc:
            raise click.UsageError("--output must be inside the repository for --workflow. Choose a repository-relative path.") from exc

    target_path.parent.mkdir(parents=True, exist_ok=True)
    target_path.write_text(json.dumps(spec, indent=2) + "\n")
    click.echo(f"✅ Wrote {target_path}")

    # Workflow file
    if workflow:
        wf_path = workflow_root / ".github/workflows/argus-probe.yml"
        wf_path.parent.mkdir(parents=True, exist_ok=True)
        target_env = ""
        if env_var and env_var != "ANTHROPIC_API_KEY":
            # The target spec reads this key at run time.
            target_env = f"          {env_var}: ${{{{ secrets.{env_var} }}}}\n"
        # The Action installs its own default version otherwise, which may predate this spec's
        # features (testbed_url "local", target-fitting `all`).
        v = _installed_version()
        # A main build's .devN version is not on PyPI, so the Action could not install it.
        version_line = f'          argus-version: "{v}"\n' if v and re.fullmatch(r"\d+\.\d+\.\d+", v) else ""
        branch_ref = _git_output("symbolic-ref", "--short", "refs/remotes/origin/HEAD")
        default_branch = branch_ref.removeprefix("origin/") if branch_ref else None
        branch_triggers = (
            f"  pull_request:\n    branches: [{json.dumps(default_branch)}]\n"
            f"  push:\n    branches: [{json.dumps(default_branch)}]\n"
            if default_branch else "  pull_request: {}\n"
        )
        wf_path.write_text(
            _WORKFLOW_TEMPLATE.format(
                target_path=json.dumps(workflow_target),
                target_env=target_env,
                probes=_probes_for(kind),
                version_line=version_line,
                branch_triggers=branch_triggers,
            )
        )
        click.echo(f"✅ Wrote {wf_path.relative_to(workflow_root)}")

    click.echo("")
    click.echo(
        f"Next: argus-probe run --local --target {shlex.quote(str(target_path))} --probes all --skip-judged "
        "--out argus-report.html"
    )
    click.echo(
        f"With a judge key: argus-probe run --local --target {shlex.quote(str(target_path))} "
        f"--probes {_probes_for(kind)} --out argus-report.html"
    )
    if workflow:
        if not default_branch:
            click.echo("Could not read the repository's default branch from git. The workflow triggers on pull_request without a branch filter; push is omitted. Set origin/HEAD with git remote set-head origin -a to generate branch filters.")
        click.echo(
            "Add ANTHROPIC_API_KEY as a repository secret for the workflow's LLM judge."
        )
