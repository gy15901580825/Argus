"""argus-probe init subcommand: scaffold a target.json + optional GH Action workflow."""

from __future__ import annotations

import json
import sys
from importlib.metadata import PackageNotFoundError, version
from pathlib import Path

import click

from argus.targets import _BUILTIN_KINDS, kinds

_DEFAULT_KIND = "openai_compat"

# Chat kinds get a small judged set. Every other kind gets `all`, because the chat probes do not
# apply to it and would be skipped, leaving a job that tests nothing. Assumes `all` fits the target (PR5a).
_CHAT_PROBES = "owasp_01_prompt_injection_basic,syscard_crescendo"


def _probes_for(kind: str) -> str:
    info = _BUILTIN_KINDS.get(kind) or kinds()[kind]
    return _CHAT_PROBES if info.chat else "all"


_WORKFLOW_TEMPLATE = """\
# .github/workflows/argus-probe.yml
# Generated by `argus-probe init`. Customize as needed.
name: argus-probe
on:
  pull_request:
    branches: [main]
  push:
    branches: [main]
  schedule:
    # Weekly Monday 06:00 UTC
    - cron: '0 6 * * 1'
  workflow_dispatch: {{}}

jobs:
  redteam:
    runs-on: ubuntu-latest
    permissions:
      security-events: write   # SARIF upload
      contents: read
    steps:
      - uses: actions/checkout@v4
      - uses: gy15901580825/argus-probe-action@v2
        env:
          # The LLM judge.
          ANTHROPIC_API_KEY: ${{{{ secrets.ANTHROPIC_API_KEY }}}}
{target_env}        with:
          target: {target_path}
          probes: {probes}
          fail-on: critical
{version_line}"""


def _installed_version() -> str | None:
    try:
        return version("argus-probe")
    except PackageNotFoundError:  # a source tree that was never installed
        return None


def _stdin_is_tty() -> bool:
    return sys.stdin.isatty()


def _ask_kind() -> str:
    descriptions = {kind: info.description for kind, info in kinds().items()}
    if not _stdin_is_tty():
        raise click.UsageError(
            "Missing option '--kind'. stdin is not a terminal, so init cannot ask for it. "
            f"Choose one of: {', '.join(descriptions)}. "
            f"Example: argus-probe init --kind {_DEFAULT_KIND}"
        )
    width = max(map(len, descriptions))
    click.echo("Which kind of target do you want to test?")
    for name, description in descriptions.items():
        click.echo(f"  {name.ljust(width)}  {description}")
    return click.prompt(
        "Target kind",
        type=click.Choice(list(descriptions)),
        default=_DEFAULT_KIND,
        show_choices=False,
    )


class _KindChoice(click.Choice):
    def __init__(self):
        # Choices are read by Click during help, conversion and completion.
        self.case_sensitive = True

    def convert(self, value, param, ctx):
        if isinstance(value, str) and value in _BUILTIN_KINDS:
            return value
        return super().convert(value, param, ctx)

    @property
    def choices(self):
        return tuple(sorted(kinds()))


@click.command("init")
@click.option(
    "--kind",
    default=None,
    type=_KindChoice(),
    help="Target adapter kind. Asked for when omitted on a terminal.",
)
@click.option(
    "--output",
    default="argus-target.json",
    show_default=True,
    help="Output target.json path",
)
@click.option(
    "--workflow/--no-workflow",
    default=None,
    help="Generate .github/workflows/argus-probe.yml (prompts if neither flag given)",
)
def init_command(kind: str | None, output: str, workflow: bool | None) -> None:
    """Generate a target.json (and optional GitHub Action workflow) for Argus."""
    click.echo(f"Argus target initializer")
    if kind is None:
        kind = _ask_kind()
    click.echo(f"Target kind: {kind}")
    info = _BUILTIN_KINDS.get(kind) or kinds()[kind]
    questions = info.init_questions
    if questions is None:
        questions = tuple((field, field, None) for field in sorted(info.required)
                          if field != "sandbox" or info.sandbox_reason is None)

    spec: dict[str, object] = {"kind": kind}
    for field, prompt_text, default in questions:
        if default is not None:
            value = click.prompt(prompt_text, default=default, show_default=True)
        else:
            value = click.prompt(prompt_text)
        spec[field] = value

    # api_key_env → api_key (CLI run command resolves $-vars at runtime)
    env_var = None
    if "api_key_env" in spec:
        env_var = str(spec.pop("api_key_env"))
        spec["api_key"] = "${" + env_var + "}"

    # inner_json → inner (payment_agent / mcp_agent / testbed_agent nest another target spec
    # for the transport that actually talks to the agent)
    if "inner_json" in spec:
        raw_inner = spec.pop("inner_json")
        try:
            spec["inner"] = json.loads(str(raw_inner))
        except json.JSONDecodeError as exc:
            raise click.UsageError(
                f"inner target spec is not valid JSON: {exc}"
            ) from exc

    if info.sandbox_reason is not None:
        spec["sandbox"] = True

    if "capabilities_csv" in spec:
        spec["capabilities"] = [
            c.strip() for c in str(spec.pop("capabilities_csv")).split(",") if c.strip()
        ]

    # Confirm-overwrite if target file exists
    target_path = Path(output)
    if target_path.exists():
        if not click.confirm(f"{output} exists. Overwrite?", default=False):
            raise click.Abort()

    target_path.write_text(json.dumps(spec, indent=2) + "\n")
    click.echo(f"✅ Wrote {target_path}")

    # Workflow file
    if workflow is None:
        workflow = click.confirm("Generate GitHub Action workflow?", default=False)
    if workflow:
        wf_path = Path(".github/workflows/argus-probe.yml")
        wf_path.parent.mkdir(parents=True, exist_ok=True)
        target_env = ""
        if env_var and env_var != "ANTHROPIC_API_KEY":
            # The target spec reads this key at run time.
            target_env = f"          {env_var}: ${{{{ secrets.{env_var} }}}}\n"
        # The Action installs its own default version otherwise, which may predate this spec's
        # features (testbed_url "local", target-fitting `all`).
        v = _installed_version()
        version_line = f'          argus-version: "{v}"\n' if v else ""
        wf_path.write_text(
            _WORKFLOW_TEMPLATE.format(
                target_path=target_path.name,
                target_env=target_env,
                probes=_probes_for(kind),
                version_line=version_line,
            )
        )
        click.echo(f"✅ Wrote {wf_path}")

    click.echo("")
    click.echo(
        f"Next: argus-probe run --local --target {target_path} --probes {_probes_for(kind)} "
        "--out argus-report.html"
    )
    if workflow:
        click.echo(
            "Add ANTHROPIC_API_KEY as a repository secret for the workflow's LLM judge."
        )
